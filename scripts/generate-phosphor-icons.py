#!/usr/bin/env python3
"""Generate src/icons/phosphor.js from the Phosphor Icons catalogue.

Phosphor ships its icons as individual SVG files on a 256x256 grid. This
script collects the path data for the icons Gramps Web uses and writes them
as a plain JavaScript module of path constants, which the app imports and
passes to <grampsjs-icon> exactly as it used to pass Material Design Icon
paths from @mdi/js.

The path data is copied verbatim — nothing is scaled or transformed. The
SVG renderer does that, from the viewBox. Scaling the numbers here would
mean re-implementing the SVG path grammar (arc flags, relative commands,
implicit command repetition) and getting it subtly wrong.

The output is committed. It is regenerated with:

    python3 scripts/generate-phosphor-icons.py

Run from the repo root, with @phosphor-icons/core installed.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOGUE = os.path.join(
    ROOT, "node_modules", "@phosphor-icons", "core", "assets", "regular"
)
MAPPING_FILE = os.path.join(ROOT, "scripts", "map-mdi-to-phosphor.py")
OUTPUT = os.path.join(ROOT, "src", "icons", "phosphor.js")

# Phosphor's grid. <grampsjs-icon> renders with this viewBox.
VIEW_BOX = 256


def pascal(name):
    return "".join(part.capitalize() for part in name.split("-"))


def load_mapping():
    """Read the MDI -> Phosphor table out of the mapping script."""
    source = open(MAPPING_FILE).read()
    pairs = re.findall(r'"(mdi[A-Za-z]+)":\s*"([a-z0-9-]+)"', source)
    return dict(pairs)


def read_icon(phosphor_name):
    path = os.path.join(CATALOGUE, phosphor_name + ".svg")
    if not os.path.exists(path):
        return None
    svg = open(path).read()
    match = re.search(r'\sd="([^"]+)"', svg)
    return match.group(1) if match else None


def main():
    if not os.path.isdir(CATALOGUE):
        sys.exit(
            "Phosphor catalogue not found at %s\n"
            "Install it with: npm install @phosphor-icons/core" % CATALOGUE
        )

    mapping = load_mapping()
    icons = {}
    for mdi_name, phosphor_name in sorted(mapping.items()):
        d = read_icon(phosphor_name)
        if d is None:
            sys.exit("icon not found in catalogue: %s" % phosphor_name)
        icons[phosphor_name] = d

    lines = [
        "/**",
        " * Phosphor Icons — path constants for Gramps Web.",
        " *",
        " * Generated by scripts/generate-phosphor-icons.py. Do not edit by",
        " * hand; edit scripts/map-mdi-to-phosphor.py and regenerate.",
        " *",
        " * Phosphor is MIT licensed, © Phosphor Icons.",
        " * https://phosphoricons.com",
        " *",
        " * Path data is on Phosphor's %dx%d grid; <grampsjs-icon> renders it"
        % (VIEW_BOX, VIEW_BOX),
        " * with the matching viewBox.",
        " */",
        "",
    ]

    for name in sorted(icons):
        lines.append("export const %s = '%s'" % (pascal(name), icons[name]))
    lines.append("")

    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w") as handle:
        handle.write("\n".join(lines))

    print(
        "wrote %s (%d icons, %d bytes)"
        % (os.path.relpath(OUTPUT, ROOT), len(icons), os.path.getsize(OUTPUT))
    )


if __name__ == "__main__":
    main()
